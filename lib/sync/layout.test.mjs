// The layout 1 → 2 upgrade: older trees are re-keyed from their content, on
// read and on disk, so promotions from snapshots taken before the file-name
// change never create or prune an item that already exists.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fakeClient } from './fake-client.mjs';
import { computePlan, runApply } from './commands.mjs';
import { MARKER, keyFor, readTree, writeTree } from './store.mjs';
import { legacySafeName, loadTree, rekeyEntries, upgradeProjectLayout, upgradeTree, treeLayout } from './layout.mjs';
import { mkdtempSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';

const emptySpaceRoutes = (space = {}) => ({
  'GET core/space': { space: { name: 'Space', slug: 'space', ...space } },
  'GET core/teams': { teams: [] },
  'GET core/fileResources': { fileResources: [] },
  'GET integrator/connections': [],
  'GET core/kapps': { kapps: [] },
  'GET core/workflows': { workflows: [] },
  'GET task/trees': { trees: [] },
  'GET task/handlers': { handlers: [] },
});

function tempProject(envs = { dev: { url: 'https://dev.example.com', readOnly: true } }) {
  const dir = mkdtempSync(join(tmpdir(), 'ksync-layout-'));
  mkdirSync(join(dir, 'environments'));
  for (const [name, def] of Object.entries(envs)) {
    writeFileSync(join(dir, 'environments', `${name}.json`), JSON.stringify(def));
    const k = name.toUpperCase();
    writeFileSync(join(dir, `.env.${name}`), `KINETIC_${k}_USERNAME=u\nKINETIC_${k}_PASSWORD=p\n`);
  }
  return dir;
}

const OLD_MARKER = 'Generated by kinetic-sync. Do not edit by hand; re-run export.\n';
const TREE = { nodes: [{ id: 'start', definitionId: 'system_start_v1' }], connectors: [] };
const TEAM = { name: 'Departments::IT', description: 'IT' };
const WORKFLOW = { name: 'Notify: approver?', event: 'Submission Submitted', filter: '', status: 'Active', notes: '', treeJson: TREE };
const ZIP = Buffer.from('PK\x03\x04 zip');
const ZIP_SHA = createHash('sha256').update(ZIP).digest('hex');

// A tree as the previous version wrote it: names through the old "_" encoding.
function writeLegacyTree(dir, items) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, MARKER), OLD_MARKER);
  for (const { parts, data, files } of items) {
    const file = join(dir, ...parts.map(legacySafeName)) + '.json';
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
    for (const [n, b] of Object.entries(files ?? {})) writeFileSync(join(dirname(file), n), b);
  }
}

const LEGACY_ITEMS = [
  { parts: ['space'], data: { name: 'Space' } },
  { parts: ['teams', 'Departments::IT'], data: TEAM },
  { parts: ['teams', 'Ops'], data: { name: 'Ops' } },
  { parts: ['workflows', 'Submission Submitted', 'Notify: approver?'], data: WORKFLOW },
  { parts: ['kapps', 'con', 'kapp'], data: { slug: 'con', name: 'Console' } },
  { parts: ['kapps', 'con', 'forms', 'f', 'form'], data: { slug: 'f', name: 'F' } },
  { parts: ['connections', 'Mail: Prod', 'connection'], data: { id: 'c-1', name: 'Mail: Prod' } },
  { parts: ['connections', 'Mail: Prod', 'operations', 'Send / now'], data: { id: 'o-1', name: 'Send / now', connectionId: 'c-1' } },
  { parts: ['handlers', 'mail_send_v1', 'handler'], data: { definitionId: 'mail_send_v1', name: 'Mail', packageSha256: ZIP_SHA }, files: { 'package.zip': ZIP } },
];

test('old keys are re-keyed from content, checked against the old file name', () => {
  const entries = new Map(LEGACY_ITEMS.map(({ parts, data }) => [parts.map(legacySafeName).join('/'), data]));
  const { keys, unresolved } = rekeyEntries(entries);
  assert.deepEqual([...unresolved], []);
  assert.equal(keys.get('teams/Departments__IT'), 'teams/Departments%3A%3AIT');
  assert.equal(keys.get('workflows/Submission Submitted/Notify_ approver_'), 'workflows/Submission Submitted/Notify%3A approver%3F');
  assert.equal(keys.get('kapps/con/kapp'), 'kapps/%63on/kapp');
  assert.equal(keys.get('kapps/con/forms/f/form'), 'kapps/%63on/forms/f/form');
  assert.equal(keys.get('connections/Mail_ Prod/operations/Send _ now'), 'connections/Mail%3A Prod/operations/Send %2F now');
  assert.equal(keys.get('teams/Ops'), 'teams/Ops');
});

test('items whose key cannot be derived for certain are unresolved, never guessed', () => {
  const { keys, unresolved } = rekeyEntries(new Map([
    ['teams/Renamed', { name: 'Something else' }],
    ['teams/Nameless', {}],
    ['teams/A_B', { name: 'A:B' }],
    ['teams/A_B_copy', { name: 'A?B' }],
    ['mystery/x', {}],
    ['kapps/we.ird/forms/f/form', { slug: 'f' }],
  ]));
  assert.deepEqual([...keys], [['teams/A_B', 'teams/A%3AB']]);
  assert.match(unresolved.get('teams/Renamed'), /does not match its file name/);
  assert.match(unresolved.get('teams/Nameless'), /cannot be read/);
  assert.match(unresolved.get('teams/A_B_copy'), /does not match/);
  assert.match(unresolved.get('mystery/x'), /not a known kind/);
  assert.match(unresolved.get('kapps/we.ird/forms/f/form'), /cannot be read/);
});

test('loadTree re-keys a layout-1 tree in memory; a current tree is read as it is', (t) => {
  const dir = join(tempProject(), 'snapshots', 'dev');
  writeLegacyTree(dir, LEGACY_ITEMS);
  const tree = loadTree(dir);
  assert.equal(tree.layout, 1);
  assert.deepEqual(tree.get('teams/Departments%3A%3AIT'), TEAM);
  assert.equal(tree.has('teams/Departments__IT'), false);
  assert.equal(tree.rekeyed.get('teams/Departments__IT'), 'teams/Departments%3A%3AIT');
  const current = join(dir, '..', 'test');
  writeTree(current, [{ key: keyFor('teams', 'A_B'), data: { name: 'A_B' } }]);
  assert.deepEqual([...loadTree(current).keys()], ['teams/A_B']);
});

function liveRoutes() {
  return {
    ...emptySpaceRoutes({ name: 'Space' }),
    'GET core/teams': { teams: [{ ...TEAM, slug: 'it' }, { name: 'Ops', slug: 'ops' }] },
    'GET core/workflows': { workflows: [{ ...WORKFLOW, id: 'w-1', platformItemType: 'Space' }] },
  };
}

function oldProject(items = LEGACY_ITEMS) {
  const dir = tempProject({ dev: { url: 'https://dev.example.com', readOnly: true }, test: { url: 'https://test.example.com' } });
  writeFileSync(join(dir, 'kinetic-sync.config.json'), JSON.stringify({ data: [], exclude: { kapps: [], forms: [] } }));
  writeLegacyTree(join(dir, 'snapshots', 'dev'), items);
  mkdirSync(join(dir, 'state'));
  writeFileSync(join(dir, 'state', 'test.json'), JSON.stringify({ 'teams/Departments__IT': 'h1', 'teams/Ops': 'h2', 'teams/Gone_': 'h3' }));
  mkdirSync(join(dir, 'overrides'));
  writeFileSync(join(dir, 'overrides', 'test.json'), JSON.stringify({ artifacts: { 'teams/Departments__IT': { description: 'IT (test)' } }, replace: [] }));
  return dir;
}

test('upgradeProjectLayout renames files from content, moves packages, re-keys state and overrides, once', () => {
  const dir = oldProject();
  const r = upgradeProjectLayout(dir);
  assert.equal(r.changed, true);
  assert.equal(r.fromLayout, 1);
  const snap = join(dir, 'snapshots', 'dev');
  assert.equal(treeLayout(snap), 2);
  assert.ok(existsSync(join(snap, 'teams', 'Departments%3A%3AIT.json')));
  assert.ok(!existsSync(join(snap, 'teams', 'Departments__IT.json')));
  assert.ok(existsSync(join(snap, 'connections', 'Mail%3A Prod', 'operations', 'Send %2F now.json')));
  assert.ok(existsSync(join(snap, 'kapps', '%63on', 'forms', 'f', 'form.json')));
  assert.deepEqual(readFileSync(join(snap, 'handlers', 'mail_send_v1', 'package.zip')), ZIP);
  assert.deepEqual(JSON.parse(readFileSync(join(dir, 'state', 'test.json'), 'utf8')), { 'teams/Departments%3A%3AIT': 'h1', 'teams/Gone_': 'h3', 'teams/Ops': 'h2' });
  assert.deepEqual(Object.keys(JSON.parse(readFileSync(join(dir, 'overrides', 'test.json'), 'utf8')).artifacts), ['teams/Departments%3A%3AIT']);
  assert.equal(JSON.parse(readFileSync(join(dir, 'kinetic-sync.config.json'), 'utf8')).layoutVersion, 2);
  assert.ok(readdirSync(join(dir, 'snapshots')).every((n) => n === 'dev'), 'no temporary folders left');
  assert.equal(upgradeProjectLayout(dir).changed, false, 'runs once');
});

for (const upgraded of [true, false]) {
  test(`a plan from a pre-upgrade snapshot (${upgraded ? 'upgraded on disk' : 're-keyed on read'}) matches the live target: nothing created, nothing pruned`, async () => {
    // Only what the live target has: the apply then has nothing to do.
    const dir = oldProject(LEGACY_ITEMS.slice(0, 4));
    if (upgraded) upgradeProjectLayout(dir);
    const calls = [];
    const clientFactory = ({ mode }) => fakeClient(liveRoutes(), { mode, calls });
    const { plan } = await computePlan({ projectDir: dir, envName: 'test', from: 'dev', clientFactory });
    const action = (k) => plan.items.find((i) => i.key === k)?.action;
    // Upgraded, the re-keyed override changes the team's description and the
    // re-keyed drift state (whose hash is not the live one) holds it back:
    // both still apply to the item under its new key.
    assert.equal(action('teams/Departments%3A%3AIT'), upgraded ? 'skip-drift' : 'unchanged');
    assert.equal(action('teams/Ops'), 'unchanged');
    assert.equal(action('workflows/Submission Submitted/Notify%3A approver%3F'), 'unchanged');
    assert.equal(plan.items.filter((i) => i.type === 'teams' || i.type === 'workflows').some((i) => i.action === 'create'), false);
    assert.deepEqual(plan.targetOnly.map((x) => x.key), []);
    const code = (await runApply({ projectDir: dir, envName: 'test', from: 'dev', yes: true, prune: ['teams', 'workflows'], log: () => {}, clientFactory })).code;
    assert.equal(code, 0);
    assert.deepEqual(calls.filter((c) => c.method === 'DELETE' || (c.method === 'POST' && /teams|workflows/.test(c.path))), []);
  });
}

test('a plan from an older tree with an item that cannot be re-keyed refuses it', async () => {
  const dir = oldProject();
  writeFileSync(join(dir, 'snapshots', 'dev', 'teams', 'Hand_edited.json'), JSON.stringify({ name: 'Not the file name' }));
  const r = upgradeProjectLayout(dir);
  assert.ok(r.notes.some((n) => n.includes('teams/Hand_edited')), r.notes.join('\n'));
  assert.equal(treeLayout(join(dir, 'snapshots', 'dev')), 1, 'left as it is');
  assert.notEqual(JSON.parse(readFileSync(join(dir, 'kinetic-sync.config.json'), 'utf8')).layoutVersion, 2);
  const clientFactory = ({ mode }) => fakeClient(liveRoutes(), { mode });
  const { plan } = await computePlan({ projectDir: dir, envName: 'test', from: 'dev', clientFactory });
  assert.ok(plan.errors.some((e) => e.startsWith('teams/Hand_edited: cannot be matched safely')), plan.errors.join('\n'));
});

test('upgradeTree on a current tree does nothing', () => {
  const dir = join(tempProject(), 'snapshots', 'dev');
  writeTree(dir, [{ key: 'teams/Ops', data: { name: 'Ops' } }]);
  assert.equal(upgradeTree(dir).upgraded, false);
  assert.deepEqual([...readTree(dir).keys()], ['teams/Ops']);
});
