// A project from before the file-name layout change, opened in the app: one
// "Upgraded project layout" commit renames its snapshot from content, and a
// changeset saved before the upgrade still plans against the live target with
// nothing created.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { PlanResult } from '../shared/sync-api.ts';
import { commitChange } from './project-meta.ts';
import { log, readTreeAt } from './repo.ts';
import { harness } from './sync-fixtures.ts';
import { commitMessage } from './trailers.ts';
// @ts-expect-error -- untyped engine module
import { legacySafeName, upgradeProjectLayout } from '../../lib/sync/layout.mjs';
// @ts-expect-error -- untyped engine module
import { decodeSegment, MARKER } from '../../lib/sync/store.mjs';

const P = '/api/projects/sync-test';
const TEAM_KEY = 'teams/Departments%3A%3AIT';
const WF_KEY = 'workflows/Submission Submitted/Notify%3A approver%3F';
const OLD_TEAM_KEY = 'teams/Departments__IT';
const OLD_WF_KEY = 'workflows/Submission Submitted/Notify_ approver_';
const TREE = { nodes: [{ id: 'start', definitionId: 'system_start_v1' }], connectors: [] };

const space = (name: string) => () => ({
  'GET core/space': { space: { name, slug: 'space', displayType: 'Display Page', webApis: [], models: [] } },
  'GET core/teams': { teams: [{ name: 'Departments::IT', slug: 'it', description: 'IT' }, { name: 'Ops', slug: 'ops', description: 'Ops' }] },
  'GET core/fileResources': { fileResources: [] },
  'GET integrator/connections': [],
  'GET core/kapps': { kapps: [] },
  'GET core/workflows': { workflows: [{ id: 'w-1', name: 'Notify: approver?', event: 'Submission Submitted', filter: '', status: 'Active', notes: '', platformItemType: 'Space', treeJson: TREE }] },
  'GET task/trees': { trees: [] },
  'GET task/handlers': { handlers: [] },
});

// Rewrites snapshots/<env> the way the previous version named its files.
function downgrade(dir: string): void {
  const snap = path.join(dir, 'snapshots', 'dev');
  const files: Array<[string, string]> = [];
  const walk = (d: string, rel: string[]) => {
    for (const name of readdirSync(d)) {
      const full = path.join(d, name);
      if (statSync(full).isDirectory()) walk(full, [...rel, name]);
      else if (name.endsWith('.json')) files.push([[...rel, name.slice(0, -5)].map((s) => legacySafeName(decodeSegment(s))).join('/'), readFileSync(full, 'utf8')]);
    }
  };
  walk(snap, []);
  rmSync(snap, { recursive: true });
  mkdirSync(snap, { recursive: true });
  writeFileSync(path.join(snap, MARKER), 'Generated by kinetic-sync. Do not edit by hand; re-run export.\n');
  for (const [key, text] of files) {
    const file = path.join(snap, ...key.split('/')) + '.json';
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  const config = path.join(dir, 'kinetic-sync.config.json');
  const { layoutVersion, ...rest } = JSON.parse(readFileSync(config, 'utf8'));
  assert.equal(layoutVersion, 2, 'new projects start on the current layout');
  writeFileSync(config, JSON.stringify(rest));
}

for (const order of ['app', 'cli'] as const) test(`a pre-upgrade project upgraded by the ${order === 'app' ? 'app on open' : 'CLI first, then opened in the app'}: its old changeset still plans with nothing created`, async (t) => {
  const h = await harness(t, { dev: true, test: false, prod: true });
  h.spaces.dev = space('Dev');
  h.spaces.test = space('Test');
  assert.equal((await h.job('POST', `${P}/snapshots`, { env: 'dev' })).status, 'succeeded');
  downgrade(h.dir);
  const ref = { id: 'sync-test', dir: h.dir };
  const oldCommit = await commitChange(ref, commitMessage('Snapshot of Dev', { Environment: 'dev' }));
  assert.ok(oldCommit);
  assert.ok((await readTreeAt(h.dir, oldCommit!, 'snapshots/dev', { raw: true })).has(OLD_TEAM_KEY));
  mkdirSync(path.join(h.dir, 'changesets'), { recursive: true });
  writeFileSync(path.join(h.dir, 'changesets', 'old-abc123.json'), JSON.stringify({
    id: 'old-abc123', name: 'Old', description: '', from: 'dev', sourceCommit: oldCommit, keys: [OLD_TEAM_KEY, OLD_WF_KEY], createdAt: '2026-01-01T00:00:00.000Z', appliedTo: [],
  }));
  await commitChange(ref, 'Saved changeset Old');

  if (order === 'cli') {
    // As `kinetic-migrate export` would: files only, the user commits.
    assert.equal(upgradeProjectLayout(h.dir).changed, true);
    await commitChange(ref, 'Upgraded by the CLI');
  }
  const opened = await h.call('POST', '/api/projects/open', { path: h.dir });
  assert.equal(opened.status, 200, opened.body);
  const [head] = await log(h.dir, { limit: 1 });
  assert.ok(existsSync(path.join(h.dir, 'snapshots', 'dev', 'teams', 'Departments%3A%3AIT.json')));
  assert.ok(!existsSync(path.join(h.dir, 'snapshots', 'dev', 'teams', 'Departments__IT.json')));
  const saved = JSON.parse(readFileSync(path.join(h.dir, 'changesets', 'old-abc123.json'), 'utf8')).keys;
  if (order === 'app') {
    assert.match(head.message, /^Upgraded project layout/);
    assert.match(head.message, /changesets\/old-abc123\.json: re-keyed/);
    assert.deepEqual(saved, [TEAM_KEY, WF_KEY]);
  } else {
    assert.equal(head.message, 'Upgraded by the CLI', 'nothing left for the app to upgrade');
    assert.deepEqual(saved, [OLD_TEAM_KEY, OLD_WF_KEY], 'still the old keys on disk');
  }
  // Either way the API shows today's keys.
  assert.deepEqual((await h.call('GET', `${P}/changesets/old-abc123`)).json.keys, [TEAM_KEY, WF_KEY]);
  // The old commit reads back under today's keys.
  const before = await readTreeAt(h.dir, oldCommit!, 'snapshots/dev');
  assert.ok(before.has(TEAM_KEY) && before.has(WF_KEY) && !before.has(OLD_TEAM_KEY));
  // Opening again changes nothing.
  await h.call('POST', '/api/projects/open', { path: h.dir });
  assert.equal((await log(h.dir, { limit: 1 }))[0].oid, head.oid);

  // The changeset is pinned to the pre-upgrade commit (old file names).
  const job = await h.job('POST', `${P}/plans`, { to: 'test', changesetId: 'old-abc123' });
  assert.equal(job.status, 'succeeded', JSON.stringify(job.error));
  const plan = job.result as PlanResult;
  assert.deepEqual(plan.errors, []);
  assert.deepEqual(plan.items.map((i) => [i.key, i.action]), [[TEAM_KEY, 'unchanged'], [WF_KEY, 'unchanged']]);
  assert.deepEqual(h.writes('test'), []);
});
